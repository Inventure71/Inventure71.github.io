function decode(text) {
  const entities = { amp: '&', lt: '<', gt: '>', quot: '"', apos: "'", nbsp: ' ', ndash: '–', mdash: '—', rsquo: '’', lsquo: '‘', rdquo: '”', ldquo: '“', hellip: '…', times: '×', rarr: '→', larr: '←', uarr: '↑', darr: '↓' };
  return text.replace(/&(#x[\da-f]+|#\d+|[a-z]+);/gi, (match, entity) => {
    if (entity.startsWith('#')) return String.fromCodePoint(entity[1].toLowerCase() === 'x' ? parseInt(entity.slice(2), 16) : Number(entity.slice(1)));
    return entities[entity] ?? match;
  });
}

// A small structural reader for our checked-in, well-formed project articles.
// Keeping a tree preserves paragraph/list boundaries and excludes navigation,
// script text and interactive example copy rather than flattening the whole page.
function parseArticle(html, file) {
  const article = html.match(/<article\b[^>]*\bid="project-story"[^>]*>([\s\S]*?)<\/article>/i)?.[1];
  if (!article) throw new Error(`Missing public project article: ${file}`);
  const tree = { tag: 'root', attrs: {}, children: [] };
  const stack = [tree];
  for (const token of article.match(/<!--[\s\S]*?-->|<[^>]+>|[^<]+/g) ?? []) {
    if (token.startsWith('<!--')) continue;
    if (token.startsWith('</')) {
      const tag = token.match(/^<\/([\w-]+)/)?.[1].toLowerCase();
      const index = stack.findLastIndex(node => node.tag === tag);
      if (index > 0) stack.length = index;
    } else if (token.startsWith('<')) {
      const tag = token.match(/^<([\w-]+)/)?.[1].toLowerCase();
      if (!tag) continue;
      const attrs = Object.fromEntries([...token.matchAll(/([\w-]+)\s*=\s*(?:"([^"]*)"|'([^']*)')/g)].map(match => [match[1], decode(match[2] ?? match[3])]));
      const node = { tag, attrs, children: [] };
      stack.at(-1).children.push(node);
      if (!voidTags.has(tag) && !token.endsWith('/>')) stack.push(node);
    } else stack.at(-1).children.push(decode(token));
  }
  return tree;
}

function skipped(node) {
  return ['nav', 'script', 'style', 'button', 'svg', 'noscript', 'iframe'].includes(node.tag)
    || node.attrs['aria-hidden'] === 'true'
    || /(?:^|\s)(?:story-actions|story-end|gs-demo|d2d-step-footer)(?:\s|$)/.test(node.attrs.class ?? '');
}
function text(node) {
  if (typeof node === 'string') return node;
  if (skipped(node)) return '';
  return node.children.map(text).join(' ').replace(/\s+/g, ' ').replace(/\s+([.,;:!?%])/g, '$1').trim();
}
function caseStudy(tree) {
  const blocks = [];
  function visit(node) {
    if (typeof node === 'string' || skipped(node)) return;
    const copy = text(node);
    if (node.attrs.role === 'img' && node.attrs['aria-label']) {
      blocks.push(node.attrs['aria-label']);
      return;
    }
    if (/^h[23]$/.test(node.tag)) blocks.push(`${'#'.repeat(Number(node.tag[1]) + 1)} ${copy}`);
    else if (['p', 'li', 'dt', 'dd', 'figcaption'].includes(node.tag)) {
      if (!copy || /(?:^|\s)story-kicker(?:\s|$)/.test(node.attrs.class ?? '')) return;
      // Inline links have a dedicated source list below; don't publish orphaned
      // calls to action such as "Watch on YouTube" as narrative paragraphs.
      if (node.tag === 'p' && !node.children.some(child => typeof child === 'string' && child.trim()) && node.children.every(child => typeof child === 'string' || child.tag === 'a')) return;
      blocks.push(node.tag === 'li' ? `- ${copy}` : node.tag === 'dt' ? `**${copy}**` : copy);
    } else for (const child of node.children) visit(child);
  }
  visit(tree);
  return blocks.join('\n\n');
}
function publicLinks(tree, href) {
  const links = new Map();
  function visit(node, inEndBlock = false) {
    if (typeof node === 'string' || node.tag === 'nav') return;
    // End blocks can mix site navigation with valid source/demo/download links.
    // Preserve those resources while excluding links to other site pages.
    const ending = inEndBlock || /(?:^|\s)story-end(?:\s|$)/.test(node.attrs.class ?? '');
    if (node.tag === 'a' && node.attrs.href) {
      const url = new URL(node.attrs.href, `${origin}${href}`);
      const siteNavigation = url.origin === origin && (url.pathname === '/projects.html' || url.hash
        || (ending && /(?:\.html|\/)$/i.test(url.pathname)));
      if (['https:', 'http:'].includes(url.protocol) && !siteNavigation) {
        const label = text(node).replace(/[↗→↓]+/g, '').trim();
        if (label && !links.has(url.href)) links.set(url.href, label);
      }
    }
    for (const child of node.children) visit(child, ending);
  }
  visit(tree);
  return [...links].map(([url, label]) => `- [${label}](${url})`).join('\n');
}
function emit(file, content) {
  const absolute = path.join(root, file);
  if (existsSync(absolute) && readFileSync(absolute, 'utf8') === content) return;
  changed++;
  if (check) console.error(`Agent content out of sync: ${file}`);
  else { mkdirSync(path.dirname(absolute), { recursive: true }); writeFileSync(absolute, content); }
}
function projectLink(project) { return `${origin}/projects/${project.id}.md`; }

const ids = new Set(ordered.map(project => project.id));
if (ids.size !== ordered.length) throw new Error('Duplicate project IDs in public catalog');
for (const id of Object.keys(context)) if (!ids.has(id)) throw new Error(`Retired project context must be reviewed: ${id}`);
for (const file of existsSync(path.join(root, 'projects')) ? readdirSync(path.join(root, 'projects')) : []) {
  if (file.endsWith('.md') && !ids.has(file.slice(0, -3))) throw new Error(`Retired Markdown project must be reviewed: projects/${file}`);
}
for (const project of ordered) {
  if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(project.id)) throw new Error(`Invalid public project ID: ${project.id}`);
  const details = context[project.id];
  if (!details?.problem || !(details?.contribution || resume.cvProjectBullets[project.id]?.[0]) || !details?.scope) throw new Error(`Missing reviewed project context: ${project.id}`);
  const html = readFileSync(path.join(root, project.href.slice(1)), 'utf8');
  const tree = parseArticle(html, project.href);
  const narrative = caseStudy(tree);
  if (narrative.length < 200) throw new Error(`Project article has too little extractable content: ${project.id}`);
  const contribution = resume.cvProjectBullets[project.id]?.[0] ?? details.contribution;
  const links = publicLinks(tree, project.href);
  emit(`projects/${project.id}.md`, `${generated}
# ${project.label}

${project.description}

- Dates: ${project.dates}
- Status: ${project.status}
- Areas: ${project.roles.map(role => roleNames.get(role) ?? role).join('; ')}
- Stack: ${project.stack}
- Topics: ${project.tags.join('; ')}
- Public case study: ${origin}${project.href}

## Problem

${details.problem}

## Contribution

${contribution}

## Technical approach and public case study

${narrative}

## Results and limitations

${details.scope}

## Public supporting links

- [Portfolio case study](${origin}${project.href})
${links ? `${links}\n` : ''}- [Matteo Giorgetti profile](${origin}/profile.md)
`);
}

function resumeSection(title, entries) {
  return `## ${title}\n\n${entries.map(entry => `### ${entry.title}\n\n${entry.organization}${entry.location ? ` · ${entry.location}` : ''} · ${entry.dates}\n${entry.badge ? `\n${entry.badge}\n` : ''}${entry.bullets?.length ? `\n${entry.bullets.map(bullet => `- ${bullet}`).join('\n')}\n` : ''}${entry.href ? `\n[Public supporting link](${entry.href})\n` : ''}`).join('\n')}`;
}
